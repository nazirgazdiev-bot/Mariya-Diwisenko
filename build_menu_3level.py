"""
Раскладывает 235 рецептов по 3-уровневой структуре меню.

Структура:
- Категория (6) — взята из PDF (поле "category")
- Подкатегория
- Подподкатегория (только где нужно)

Принципы:
- Каждый рецепт = в ровно одной конечной подкатегории (никаких дублей).
- Распределение строго по правилам ниже. Категория верхнего уровня берётся
  из PDF и не меняется.
- Проверки в конце: сумма по всем конечным = 235, каждый id ровно один раз.
"""

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

# Скрипт принимает на вход menu.json от parse_pdf_v2.py (одноуровневая структура
# с recipes) и переписывает его в 3-уровневую структуру.
# Чтобы можно было перезапускать — читаем и пишем в один и тот же файл.
IN_JSON = Path(__file__).parent / "menu.json"
OUT_JSON = Path(__file__).parent / "menu.json"


def match_any(name: str, *kws) -> bool:
    n = name.lower()
    return any(k.lower() in n for k in kws)


# ============ ПРАВИЛА КЛАССИФИКАЦИИ ============

def classify_first_courses(name: str) -> str:
    """Первые блюда — 3 подкатегории, без 3 уровня."""
    if match_any(name, "крем-суп", "крем -суп"):
        return "Крем-супы"
    if match_any(name, "холодный", "холодн"):
        return "Холодные супы"
    return "Горячие супы"


def classify_meat(name: str) -> tuple[str, str | None]:
    """
    Блюда из мяса — 3 подкатегории + 3-й уровень в Курице и Говядине.
    """
    n = name.lower()

    # ВАЖНО: сначала определяем содержит ли название курицу, чтобы курица
    # не утекла в субпродукты или говядину.
    # Корень для курицы — "курин" (куриное, куриная, куриный, куриные, куриным...)
    is_chicken = match_any(name, "курин", "куриц")
    is_turkey = match_any(name, "индейк")

    # 1. СУБПРОДУКТЫ — только если НЕТ курицы/индейки в названии.
    # ("печен" может ловить "печенье" но в мясе печенья нет; зато "Запеченный картофель
    # с куриным филе" не должен сюда попасть — он содержит "куриным")
    if not (is_chicken or is_turkey):
        if match_any(name, "печёнк", "печёночн", "печеночн", "печень ", " печени",
                     "сердечк", "язык"):
            return ("Субпродукты", None)
        # Печёночные оладьи / отбивные из печени тоже сюда
        if match_any(name, "печёночн", "печеночн", "печёночные", "печеночные",
                     "отбивные из печени"):
            return ("Субпродукты", None)
    # Куриные сердечки — субпродукт, но содержит "куриные". Особый случай:
    if match_any(name, "сердечк"):
        return ("Субпродукты", None)
    # Печень в названии (без "куриный") — субпродукт
    if (not is_chicken) and match_any(name, "печень"):
        return ("Субпродукты", None)
    if match_any(name, "печёночные оладьи", "печеночные оладьи", "отбивные из печени",
                 "печёночный паштет", "печеночный паштет", "отварной язык",
                 "салат из языка"):
        return ("Субпродукты", None)

    # 2. КУРИЦА И ИНДЕЙКА
    if is_chicken or is_turkey:
        # Запеканки/духовка/бёдра/ножки/пироги/наггетсы/маффины/фаршированные
        if match_any(name, "запеканк", "духовк", "бедра", "бёдра", "ножк", "крыл",
                     "запечённ", "запечен", "наггетс", "маффин",
                     "под шапочкой", "перец, фарширован",
                     "куриные отбивные", "картофельные гнезда",
                     "фаршированный перец",
                     "3аливной пирог с курицей", "заливной пирог с курицей",
                     "куриные ножки с рисом в духовке",
                     "мясные конвертики"):
            return ("Курица и индейка", "Запеканки, пироги, бёдра и ножки в духовке")
        # Курица с гарниром (паста/гречка/плов/фунчоза/спагетти)
        if match_any(name, "паст", "макарон", "плов", "фунчоз", "спагетти",
                     "гречка с курицей", "гречка с курин", "карбонар"):
            return ("Курица и индейка", "Курица с гарниром (паста, гречка, плов)")
        # Котлеты/тефтели/фрикадельки/биточки/оладьи рубленые/колбаса/сосиски
        # (колбаса и сосиски — это переработанное мясо, по формату ближе к котлетам)
        if match_any(name, "котлет", "тефтел", "фрикадельк", "биточк", "оладьи рубленые",
                     "куриные оладьи", "куриная колбаса", "куриные сосиски"):
            return ("Курица и индейка", "Котлеты, тефтели, фрикадельки")
        # Индейка отдельно — только если индейка БЕЗ курицы
        if is_turkey and not is_chicken:
            return ("Курица и индейка", "Индейка")
        # Иначе — куриное филе на сковороде/в соусах
        return ("Курица и индейка", "Куриное филе на сковороде и в соусах")

    # 3. ГОВЯДИНА И СВИНИНА (всё остальное)
    # Котлеты/тефтели/биточки из мяса
    if match_any(name, "котлет", "тефтел", "фрикадельк", "биточк", "гречаник",
                 "рубленный", "рубленые"):
        return ("Говядина и свинина", "Котлеты, тефтели, биточки")
    # Лазанья/паста/макароны
    if match_any(name, "лазань", "паст", "макарон", "карбонар", "плов",
                 "макароны по-флотски"):
        return ("Говядина и свинина", "Лазанья, паста, макароны с мясом")
    # Запеканки и в духовке
    if match_any(name, "запеканк", "духовк", "по-французск", "буженин",
                 "запечён", "запечен", "гнезд", "зразы", "под шапочкой",
                 "ленивые пельмени", "конвертик", "ленивая лазанья",
                 "рваный пирог из лаваша"):
        return ("Говядина и свинина", "Запеканки и в духовке")
    # Иначе — тушёное и на сковороде
    return ("Говядина и свинина", "Тушёное и на сковороде")


def classify_fish(name: str) -> str:
    """Блюда из рыбы — 2 подкатегории, без 3 уровня."""
    if match_any(name, "креветк", "кальмар", "мидии", "морепродукт", "осьминог"):
        return "Морепродукты"
    return "Рыбные блюда"


def classify_salads_zakuski(name: str) -> tuple[str, str | None]:
    """
    Салаты, закуски, завтраки, несладкая выпечка — 4 подкатегории.
    Завтраки и Несладкая выпечка имеют 3-й уровень.
    """
    n = name.lower()

    # 1. Завтраки сладкие — только явно сладкие (с фруктами/шоколадом/морковью)
    if match_any(name, "морковные оладьи", "запеченная овсянка", "запечённая овсянка",
                 "шоколадно-вишневая овсянка",
                 "запеченные боулы на завтрак", "запечённые боулы на завтрак"):
        return ("Завтраки", "Сладкие")

    # 2. Завтраки несладкие — омлеты, шакшуки + блины/вафли из раздела
    # «несладкая выпечка» Маши (овсяноблин, рисовый блин, рисовые вафли — нейтральные)
    if match_any(name, "шакшука", "омлет", "отмлет", "яичница", "хлеб в яйце",
                 "ленивые хачапури", "ленивый хачапури из лаваша",
                 "горячие высокобелковые бутерброды",
                 "гречка с яйцами", "яйца с начинкой",
                 "овсяноблин", "рисовый блин", "рисовай блин", "рисовые вафли",
                 "сытный гречневый боул"):
        return ("Завтраки", "Несладкие")

    # 3. Салаты (явные — содержат "салат")
    if match_any(name, "салат") and not match_any(name, "заправк"):
        return ("Салаты", None)
    # Заправки для салатов — тоже в салаты
    if match_any(name, "заправк"):
        return ("Салаты", None)

    # 4. Несладкая выпечка
    # 4а. ПП-фастфуд (пицца, бургер, шаурма)
    if match_any(name, "пицца", "бургер", "шаурма"):
        return ("Несладкая выпечка", "Пицца, бургеры, шаурма (ПП-фастфуд)")
    # 4б. Чебуреки, наггетсы, рулеты, лаваш (объединённая категория)
    if match_any(name, "чебурек", "наггетс", "пельмени", "конвертик",
                 "рулет", "тортилья", "тортильe", "тортилье", "роллы",
                 "завертон", "улитка из рисовой бумаги",
                 "несладкий творожный пирог", "блинный торт с красной рыбой",
                 "картофельные лепешки", "быстрые пирожки",
                 "лаваш", "хачапури", "рваный пирог"):
        return ("Несладкая выпечка", "Чебуреки, рулеты, лаваш-блюда")

    # Всё остальное — Закуски и намазки
    return ("Закуски и намазки", None)


def classify_garnish(name: str) -> str:
    """Гарниры и каши — 3 подкатегории, без 3 уровня."""
    if match_any(name, "картоф", "картош"):
        return "Картофель"
    # Каши, крупы, боулы
    if match_any(name, "гречк", "рис", "булгур", "каша", "боул"):
        return "Каши и крупы"
    return "Овощные"


def classify_desserts(name: str) -> tuple[str, str | None]:
    """Десерты — 4 подкатегории, у Выпечки и Прочих сладостей есть 3 уровень."""
    n = name.lower()

    # 1. Творожные десерты и запеканки
    if match_any(name, "сырник", "ленивые вареники", "творожн", "тирамису",
                 "чизкейк", "ватрушк", "пудинг", "баунти-творож",
                 "запеканка из тыквы и творога", "клафути"):
        # "Творожная запеканка" — да
        # "Творожный кекс" — да (творожное)
        # "Творожный пудинг" — да
        # "Творожная галета" — да
        return ("Творожные десерты и запеканки", None)

    # 2. Сладкие блины, оладьи, панкейки, вафли
    if match_any(name, "блин", "панкейк", "пакейк", "оладьи", "вафл",
                 "начинки для блинов"):
        # Все сладкие (мясные оладьи здесь не появятся — они в Мясе)
        return ("Сладкие блины, оладьи, панкейки", None)

    # 3. Прочие сладости — с 3 уровнем
    # 3а. Печенье и пирожные
    if match_any(name, "печенье", "печенья", "печений", "печен ",
                 "пирожн", "кокосанка", "безе"):
        return ("Прочие сладости", "Печенье и пирожные")
    # 3б. Шоколадные десерты
    if match_any(name, "шоколад", "брауни", "пп печенье баунти",
                 "пп-баунти", "баунти-творожок"):
        # "Баунти-творожок" уже в Творожных — повторно не попадёт
        return ("Прочие сладости", "Шоколадные десерты")
    # 3в. Муссы, желе, мороженое
    if match_any(name, "панна-котта", "птичье молоко", "манго-десерт",
                 "мороженое", "суфле", "желе"):
        return ("Прочие сладости", "Муссы, желе, мороженое")

    # 4. Выпечка — без 3 уровня (объединено: торты, кексы, пироги, штрудели, рулеты)
    if match_any(name, "торт", "кекс", "манник",
                 "пирог", "штрудель", "рулет", "наполеон", "шарлотка",
                 "галета", "булочки", "синнабон", "пицца"):
        return ("Выпечка", None)

    # Fallback — если ничего не подошло, кладём в "Прочие сладости / Муссы..."
    return ("Прочие сладости", "Муссы, желе, мороженое")


# ============ ОСНОВНОЙ ПРОЦЕСС ============

CATEGORIES_TOP = [
    "Первые блюда",
    "Блюда из мяса",
    "Блюда из рыбы",
    "Салаты, закуски, завтраки, несладкая выпечка",
    "Гарниры и каши",
    "Десерты и сладкая выпечка",
]


def classify_one(recipe: dict) -> tuple[str, str, str | None]:
    """Возвращает (category, sub, subsub_or_None)."""
    cat = recipe["category"]
    name = recipe["name"]

    if cat == "Первые блюда":
        return (cat, classify_first_courses(name), None)
    if cat == "Блюда из мяса":
        sub, subsub = classify_meat(name)
        return (cat, sub, subsub)
    if cat == "Блюда из рыбы":
        return (cat, classify_fish(name), None)
    if cat == "Салаты, закуски, завтраки, несладкая выпечка":
        sub, subsub = classify_salads_zakuski(name)
        return (cat, sub, subsub)
    if cat == "Гарниры и каши":
        return (cat, classify_garnish(name), None)
    if cat == "Десерты и сладкая выпечка":
        sub, subsub = classify_desserts(name)
        return (cat, sub, subsub)
    raise ValueError(f"Неизвестная категория: {cat}")


def build_menu(recipes: list[dict]) -> dict:
    """
    Строит дерево меню.
    Формат для подкатегории:
    - list[str] — если нет 3 уровня
    - dict[str, list[str]] — если есть 3 уровень
    """
    tree: dict = {cat: {} for cat in CATEGORIES_TOP}
    for r in recipes:
        cat, sub, subsub = classify_one(r)
        if subsub is None:
            # Лист = list[str]
            if sub not in tree[cat]:
                tree[cat][sub] = []
            if isinstance(tree[cat][sub], dict):
                raise ValueError(f"Конфликт уровней в {cat}/{sub}: уже dict, пытаемся list")
            tree[cat][sub].append(r["id"])
        else:
            # Двухуровневый: dict[str, list[str]]
            if sub not in tree[cat]:
                tree[cat][sub] = {}
            if isinstance(tree[cat][sub], list):
                raise ValueError(f"Конфликт уровней в {cat}/{sub}: уже list, пытаемся dict")
            if subsub not in tree[cat][sub]:
                tree[cat][sub][subsub] = []
            tree[cat][sub][subsub].append(r["id"])
    return tree


def collect_all_ids(tree: dict) -> list[str]:
    """Собирает все id рецептов из дерева в плоский список."""
    out = []
    for cat, subs in tree.items():
        for sub, val in subs.items():
            if isinstance(val, list):
                out.extend(val)
            elif isinstance(val, dict):
                for subsub, ids in val.items():
                    out.extend(ids)
    return out


def main():
    data = json.loads(IN_JSON.read_text(encoding="utf-8"))
    recipes = data["recipes"]
    print(f"Загружено: {len(recipes)} рецептов из {IN_JSON.name}")

    tree = build_menu(recipes)

    # === ПРОВЕРКИ ===
    all_ids = collect_all_ids(tree)
    expected_ids = [r["id"] for r in recipes]
    print(f"В дереве: {len(all_ids)} назначений")
    print(f"Уникальных id в дереве: {len(set(all_ids))}")
    print(f"Ожидается: {len(expected_ids)}")

    # Дубли
    dup_ids = [i for i in all_ids if all_ids.count(i) > 1]
    if dup_ids:
        print(f"⚠ ДУБЛИКАТЫ ({len(set(dup_ids))}): {sorted(set(dup_ids))[:20]}")
    # Пропущенные
    missing = set(expected_ids) - set(all_ids)
    if missing:
        print(f"⚠ ПРОПУЩЕНО ({len(missing)}): {sorted(missing)[:20]}")

    if len(set(all_ids)) == len(expected_ids) and not dup_ids:
        print("✓ Все рецепты на месте, без дублей")

    # === СОХРАНЯЕМ ===
    out = {
        "title": data.get("title", ""),
        "categories": CATEGORIES_TOP,
        "menu": tree,
        "total": len(recipes),
        "recipes": recipes,
    }
    OUT_JSON.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n✓ Сохранено в {OUT_JSON.name}")


if __name__ == "__main__":
    main()

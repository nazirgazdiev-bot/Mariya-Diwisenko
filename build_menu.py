"""
Разносит все рецепты из recipes.json по новой структуре меню (8 категорий, 2-4 подкатегории каждая).

Один рецепт может попасть в несколько подкатегорий — это нормально (например
"Творожная запеканка" подходит и под «Завтраки/Сладкие», и под «Десерты/Творожные»).

Логика классификации:
- По ключевым словам в названии.
- С учётом исходной категории из PDF (как подсказка).
- Если рецепт не попал никуда — отметим в unclassified.
"""

